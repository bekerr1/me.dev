# Agents: one shared instruction file, wired into every harness, plus the
# third-party tooling pinned in tools.env.

# shellcheck disable=SC1091
. "$ME_ROOT/tools.env"

# --- the shared instruction file ------------------------------------------

link "$ME_ROOT/agents/AGENTS.md" "$ME_STATE/AGENTS.md"
link "$ME_ROOT/agents/AGENTS.md" "$HOME/.codex/AGENTS.md"
link "$ME_ROOT/agents/AGENTS.md" "$HOME/.pi/agent/AGENTS.md"

# ~/AGENTS.md used to be the Pi fallback, linked before the manifest existed.
# Pi also reads AGENTS.md from every parent of the working directory and
# dedupes by path, not by symlink target, so alongside ~/.pi/agent/AGENTS.md it
# would load the instructions twice.
retire "$HOME/AGENTS.md"

link "$ME_ROOT/agents/claude/CLAUDE.md" "$HOME/.claude/CLAUDE.md"
link "$ME_ROOT/agents/claude/settings.json" "$HOME/.claude/settings.json"

# Cursor rules cannot reference another file, so the .mdc is generated by
# concatenating the frontmatter header with AGENTS.md.
generate "$HOME/.cursor/rules/agents.mdc" \
  < <(cat "$ME_ROOT/agents/cursor/frontmatter.mdc" "$ME_ROOT/agents/AGENTS.md")

# --- third-party agent tooling --------------------------------------------
#
# All of it installs on every machine. These are part of the working setup, not
# extras -- having to remember a flag to get them is the same as not having them.
# `--minimal` (servers, jump boxes) and `--no-net` still skip the lot.

section tools
if [[ $ME_MINIMAL == 1 || $ME_NO_NET == 1 ]]; then
  partial "skipping agent tooling (--minimal/--no-net)"
  return 0 2>/dev/null || true
fi

# mattpocock/skills. The installer always hits the network, so the version last
# installed is stamped and the step only runs again when the pin changes.
skills_stamp="$ME_STATE/state/skills"
skills_want="$SKILLS_SOURCE skills@$SKILLS_NPM_VERSION"
if [[ -d $HOME/.agents/skills && "$(cat "$skills_stamp" 2>/dev/null)" == "$skills_want" ]]; then
  skip "$SKILLS_SOURCE at skills@$SKILLS_NPM_VERSION"
elif have npx; then
  if [[ $ME_DRY_RUN == 1 ]]; then
    ok "dry run: would install $SKILLS_SOURCE via skills@$SKILLS_NPM_VERSION"
  else
    log "  installing $SKILLS_SOURCE (skills@$SKILLS_NPM_VERSION)"
    # Skills land in ~/.agents/skills and are symlinked into each harness's own
    # skills directory. The installer writes skills-lock.json into the working
    # directory, so run it from $HOME to keep the lock global rather than
    # dropping one into this repo.
    if ( cd "$HOME" && npx --yes "skills@$SKILLS_NPM_VERSION" add "$SKILLS_SOURCE" </dev/null ); then
      mkdir -p "$(dirname "$skills_stamp")"
      printf '%s\n' "$skills_want" > "$skills_stamp"
      ok "$SKILLS_SOURCE installed to ~/.agents/skills -- run /setup-matt-pocock-skills once per repo"
    else
      warn "skills install failed; run manually: npx skills@$SKILLS_NPM_VERSION add $SKILLS_SOURCE"
    fi
  fi
else
  warn "npx not found -- skipping $SKILLS_SOURCE"
fi

# firstmate -- a distro you run a harness inside, so it is cloned rather than
# installed as a binary. Pinned by commit; upstream cuts no releases.
clone_pinned firstmate "$FIRSTMATE_REPO" "$FIRSTMATE_REF" "$FIRSTMATE_HOME"
have gh || warn "firstmate needs an authenticated gh; run: gh auth login"

# no-mistakes -- validation pipeline in front of `git push`.
if install_release_binary no-mistakes kunchenguid/no-mistakes "$NO_MISTAKES_VERSION"; then
  log "  run 'no-mistakes init' inside a repo to add the push target"
fi

# treehouse -- git worktree management.
if install_release_binary treehouse kunchenguid/treehouse "$TREEHOUSE_VERSION"; then
  log "  run 'treehouse --help' to get started"
fi

# Pi -- agent harness. Reads ~/.pi/agent/AGENTS.md (linked above) and the
# ~/.agents/skills directory the skills installer fills, so needs no other wiring.
install_pi "$PI_VERSION"
