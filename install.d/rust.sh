# Rust: rustup plus a pinned default toolchain, with rust-analyzer and rust-src
# for Cursor. rustup rather than pixi so each project's rust-toolchain.toml is
# honoured and targets/components can be added.
#
# rustup-init is fetched directly at a pinned version (and checksum-verified)
# instead of through the rustup.rs curl|sh script, which always takes the latest.
# --no-modify-path: shell/rc.d/10-path.sh already puts ~/.cargo/bin on PATH.
#
# ~/.cargo and ~/.rustup are not owned, so never pruned: they also hold
# everything you `cargo install` and the toolchains projects ask for.

# shellcheck disable=SC1091
. "$ME_ROOT/tools.env"

# Linker. In the shell, pixi's cc is first on PATH; Cursor started from the
# desktop has no cc on PATH at all. Pin cargo to the system one (packages.sh)
# so both link the same way, against system libraries only.
if [[ $(os_name) == linux ]]; then
  case "$(uname -m)" in
    x86_64|amd64)  rust_target=x86_64-unknown-linux-gnu ;;
    aarch64|arm64) rust_target=aarch64-unknown-linux-gnu ;;
  esac
  [[ -n ${rust_target:-} ]] && generate "$HOME/.cargo/config.toml" <<CARGO
# Generated by install.d/rust.sh in the me repo; local edits are overwritten.
[target.$rust_target]
linker = "/usr/bin/cc"
CARGO
fi

section toolchain
if [[ $ME_NO_NET == 1 ]]; then
  partial "not installing rust (--no-net)"
  return 0 2>/dev/null || true
fi

rustup="$HOME/.cargo/bin/rustup"
components=(rust-analyzer rust-src rustfmt clippy)

if [[ -x $rustup ]] && "$rustup" --version 2>/dev/null | grep -qF "rustup $RUSTUP_VERSION "; then
  skip "rustup $RUSTUP_VERSION"
elif [[ $ME_DRY_RUN == 1 ]]; then
  ok "dry run: would install rustup $RUSTUP_VERSION"
else
  case "$(os_name)-$(uname -m)" in
    linux-x86_64)               target=x86_64-unknown-linux-gnu ;;
    linux-aarch64|linux-arm64)  target=aarch64-unknown-linux-gnu ;;
    macos-x86_64)               target=x86_64-apple-darwin ;;
    macos-arm64)                target=aarch64-apple-darwin ;;
    *) warn "rust: unsupported platform $(os_name)-$(uname -m)"; return 0 ;;
  esac
  url="https://static.rust-lang.org/rustup/archive/$RUSTUP_VERSION/$target/rustup-init"
  tmp=$(mktemp -d)
  if curl -fsSL "$url" -o "$tmp/rustup-init" && curl -fsSL "$url.sha256" -o "$tmp/sum" \
     && [[ "$(cut -d' ' -f1 "$tmp/sum")" == "$( (sha256sum "$tmp/rustup-init" 2>/dev/null || shasum -a 256 "$tmp/rustup-init") | cut -d' ' -f1)" ]]; then
    chmod +x "$tmp/rustup-init"
    # Installs or upgrades rustup in place; the toolchain is handled below.
    if "$tmp/rustup-init" -y --no-modify-path --profile minimal --default-toolchain none >/dev/null 2>&1; then
      ok "rustup $RUSTUP_VERSION -> ~/.cargo/bin"
    else
      warn "rustup-init failed; run it by hand: $url"
    fi
  else
    warn "rust: could not fetch or verify $url"
  fi
  rm -rf "$tmp"
fi

if [[ ! -x $rustup ]]; then
  [[ $ME_DRY_RUN == 1 ]] || warn "rustup missing; skipping the toolchain"
  return 0 2>/dev/null || true
fi

# The pinned toolchain, its components, and making it the default. Each check
# is local, so a re-run with everything in place touches nothing.
have_toolchain() { "$rustup" toolchain list 2>/dev/null | grep -q "^$RUST_VERSION-"; }
missing_components() {
  local installed c
  installed=$("$rustup" component list --installed --toolchain "$RUST_VERSION" 2>/dev/null)
  for c in "${components[@]}"; do
    grep -q "^$c\(-\|$\)" <<< "$installed" || printf '%s ' "$c"
  done
}

if have_toolchain && [[ -z $(missing_components) ]]; then
  skip "rust $RUST_VERSION with ${components[*]}"
elif [[ $ME_DRY_RUN == 1 ]]; then
  ok "dry run: would install rust $RUST_VERSION with ${components[*]}"
else
  log "  installing rust $RUST_VERSION (a few hundred MB)"
  if "$rustup" toolchain install "$RUST_VERSION" --profile minimal \
       --component "$(IFS=,; echo "${components[*]}")" >/dev/null 2>&1; then
    ok "rust $RUST_VERSION with ${components[*]}"
  else
    warn "rustup toolchain install $RUST_VERSION failed; run it by hand to see why"
  fi
fi

if [[ "$("$rustup" default 2>/dev/null)" == "$RUST_VERSION-"* ]]; then
  skip "default toolchain $RUST_VERSION"
elif [[ $ME_DRY_RUN == 1 ]]; then
  ok "dry run: would make $RUST_VERSION the default toolchain"
elif have_toolchain && "$rustup" default "$RUST_VERSION" >/dev/null 2>&1; then
  ok "default toolchain $RUST_VERSION"
fi
